# Schemas Pydantic
"""Data models and schemas for Call-me-maybe."""

from typing import Dict, Literal, Optional, Union
from pydantic import (
    BaseModel,
    Field,
    StrictBool,
    StrictFloat,
    StrictInt,
    StrictStr,
)


class ParameterDefinition(BaseModel):
    """Schema for individual parameter specifications."""

    type: Literal["string", "number", "integer", "boolean"]
    description: Optional[str] = None


class ReturnDefinition(BaseModel):
    """Schema for return type definitions."""

    type: str


class FunctionDefinition(BaseModel):
    """Schema for function definitions from functions_definition.json."""

    name: str
    description: str
    parameters: Dict[str, ParameterDefinition] = Field(default_factory=dict)
    returns: Optional[ReturnDefinition] = None


class TestCase(BaseModel):
    """Schema for individual prompts from function_calling_tests.json."""

    prompt: str


ArgumentValue = Union[StrictBool, StrictInt, StrictFloat, StrictStr]


class ToolCall(BaseModel):
    """Schema for the constrained output generated by the LLM."""

    name: str
    parameters: Dict[str, ArgumentValue] = Field(default_factory=dict)


class ResultEntry(BaseModel):
    """Schema for each entry in the final output JSON file."""

    prompt: str
    name: str
    parameters: Dict[str, ArgumentValue]
